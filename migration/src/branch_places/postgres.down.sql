-- Gives the service its own list of branch places again on PostgreSQL (docs/schema.md).

CREATE TABLE "branch_agents" (
  "pool" text NOT NULL DEFAULT '',
  "slot" bigint NOT NULL,
  "mode" text NOT NULL,
  "model" text NOT NULL,
  "role" text NOT NULL,
  "upstream" text NOT NULL DEFAULT '',
  "prefix_digest" text NOT NULL DEFAULT '',
  "last_reply_at" bigint NOT NULL,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("pool", "slot", "mode", "model", "upstream")
);
